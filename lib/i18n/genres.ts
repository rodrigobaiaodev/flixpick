export function getLocalizedRefineLabel(
  locale: Locale,
  englishLabel: string,
  genreId?: number,
): string {
  const fromMap = REFINE_CHIP_LABELS[locale]?.[englishLabel];
  if (fromMap) return fromMap;
  if (genreId != null) return getLocalizedGenreName(locale, genreId, englishLabel);
  return englishLabel;
}

export function getGenreOptions(locale: Locale) {
  return Object.entries(GENRE_LABELS[locale] ?? GENRE_LABELS.en).map(
    ([id, name]) => ({ id: Number(id), name }),
  );
}
