export function getLocalizedGenreName(
  locale: Locale,
  id: number,
  fallbackName?: string,
): string {
  const localized = GENRE_LABELS[locale]?.[id];
  if (localized) return localized;
  if (fallbackName && !/^Genre \d+$/.test(fallbackName)) return fallbackName;
  return GENRE_LABELS.en[id] ?? "Unknown";
}

